export function translate(lang, key, vars) {
  const dict = translations[lang] || translations.en;
  let s = dict[key] ?? translations.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
  return s;
}
